"""
LLM Integration Framework for Vision-Language-Action (VLA) System

This module provides the core infrastructure for integrating large language models
with the robotic system, including prompt engineering utilities and response parsing.
"""

import os
import json
import logging
from abc import ABC, abstractmethod
from typing import Dict, List, Optional, Any
from dataclasses import dataclass
from enum import Enum


class LLMProvider(Enum):
    """Supported LLM providers"""
    OPENAI = "openai"
    ANTHROPIC = "anthropic"
    OLLAMA = "ollama"
    HUGGINGFACE = "huggingface"


@dataclass
class LLMConfig:
    """Configuration for LLM integration"""
    provider: LLMProvider
    api_key: str
    model: str
    temperature: float = 0.7
    max_tokens: int = 1000
    timeout: int = 30


@dataclass
class ActionStep:
    """Represents a single action step generated by the LLM"""
    action_type: str  # e.g., "move_to", "grasp", "detect_object"
    parameters: Dict[str, Any]
    description: str


class LLMInterface(ABC):
    """Abstract base class for LLM providers"""

    @abstractmethod
    async def generate_response(self, prompt: str) -> str:
        """Generate a response from the LLM"""
        pass

    @abstractmethod
    def validate_config(self, config: LLMConfig) -> bool:
        """Validate the LLM configuration"""
        pass


class LLMManager:
    """Main class for managing LLM integration"""

    def __init__(self, config: LLMConfig):
        self.config = config
        self.provider = self._initialize_provider()
        self.logger = logging.getLogger(__name__)

    def _initialize_provider(self) -> LLMInterface:
        """Initialize the appropriate LLM provider based on config"""
        if self.config.provider == LLMProvider.OPENAI:
            return OpenAILLM(self.config)
        elif self.config.provider == LLMProvider.ANTHROPIC:
            return AnthropicLLM(self.config)
        elif self.config.provider == LLMProvider.OLLAMA:
            return OllamaLLM(self.config)
        elif self.config.provider == LLMProvider.HUGGINGFACE:
            return HuggingFaceLLM(self.config)
        else:
            raise ValueError(f"Unsupported LLM provider: {self.config.provider}")

    async def plan_action_sequence(self, command: str, context: str = "") -> List[ActionStep]:
        """Generate an action sequence from a natural language command"""
        try:
            # Create a structured prompt for action planning
            prompt = self._create_action_planning_prompt(command, context)

            # Get response from LLM
            response = await self.provider.generate_response(prompt)

            # Parse the response into action steps
            action_steps = self._parse_action_sequence(response)

            self.logger.info(f"Generated {len(action_steps)} action steps for command: {command}")
            return action_steps
        except Exception as e:
            self.logger.error(f"Error planning action sequence: {e}")
            raise

    def _create_action_planning_prompt(self, command: str, context: str) -> str:
        """Create a structured prompt for action planning"""
        return f"""
        You are a robotics planning assistant. Convert the following natural language command into a sequence of specific robotic actions.

        Context: {context}
        Command: {command}

        Respond with a JSON array of action steps, where each step has:
        - action_type: The type of action (e.g., "move_to", "grasp", "detect_object", "navigate")
        - parameters: A dictionary of parameters needed for the action
        - description: A human-readable description of the action

        Example response format:
        [
            {{
                "action_type": "detect_object",
                "parameters": {{"object_type": "cup", "color": "red"}},
                "description": "Detect a red cup on the table"
            }},
            {{
                "action_type": "move_to",
                "parameters": {{"target_location": "table_1"}},
                "description": "Move to the table where the cup is located"
            }}
        ]

        Respond only with the JSON array, no additional text.
        """

    def _parse_action_sequence(self, response: str) -> List[ActionStep]:
        """Parse the LLM response into action steps"""
        try:
            # Try to find JSON in the response
            json_start = response.find('[')
            json_end = response.rfind(']') + 1

            if json_start != -1 and json_end != 0:
                json_str = response[json_start:json_end]
                action_data = json.loads(json_str)

                action_steps = []
                for step_data in action_data:
                    action_step = ActionStep(
                        action_type=step_data.get('action_type', ''),
                        parameters=step_data.get('parameters', {}),
                        description=step_data.get('description', '')
                    )
                    action_steps.append(action_step)

                return action_steps
            else:
                # If no JSON found, create a simple action
                return [ActionStep(
                    action_type="unknown",
                    parameters={"raw_response": response},
                    description="Unknown action from LLM response"
                )]
        except json.JSONDecodeError as e:
            self.logger.error(f"Error parsing LLM response as JSON: {e}")
            return [ActionStep(
                action_type="error",
                parameters={"error": str(e), "raw_response": response},
                description="Error parsing LLM response"
            )]

    async def validate_plan(self, action_sequence: List[ActionStep]) -> bool:
        """Validate that the action sequence is feasible"""
        # Basic validation - in a real implementation, this would check
        # for action conflicts, resource availability, etc.
        for step in action_sequence:
            if not step.action_type or not step.description:
                return False
        return True


