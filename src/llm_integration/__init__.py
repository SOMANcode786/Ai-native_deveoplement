# Utility functions for prompt engineering
def create_robotics_prompt_template(intent: str, constraints: List[str] = None) -> str:
    """Create a standardized prompt template for robotics tasks"""
    constraints_text = ""
    if constraints:
        constraints_text = f"Constraints: {', '.join(constraints)}"

    return f"""
    As a robotics planning assistant, your task is to convert high-level commands into executable robotic actions.

    Intent: {intent}
    {constraints_text}

    Provide a sequence of specific, executable actions that a robot can perform.
    """